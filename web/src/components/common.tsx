export function Avatar({
  user, avatar, size = 46, shape, frame, badge, story, onClick, className, playVideo = true, title,
}: {
  user?: PublicUser | null;
  avatar?: any;
  size?: number;
  shape?: 'circle' | 'squircle';
  frame?: { style: string; color: string };
  badge?: React.ReactNode;
  story?: 'unseen' | 'seen' | boolean;
  onClick?: (e: React.MouseEvent) => void;
  className?: string;
  playVideo?: boolean;
  title?: string;
}) {
  const av = avatar ?? user?.avatar ?? null;
  const sh = shape ?? (user?.settings?.avatarShape as any) ?? 'circle';
  const fr = frame ?? user?.settings?.avatarFrame ?? { style: 'none', color: '' };
  const ref = useRef<HTMLDivElement>(null);
  const [inView, setInView] = useState(false);
  const [muted, setMuted] = useState(true);
  const [videoMuted, setVideoMuted] = useState(true);

  useEffect(() => {
    if (av?.kind !== 'video' || !playVideo) return;
    const el = ref.current;
    if (!el) return;
    const obs = new IntersectionObserver((es) => {
      setInView(es[0]?.isIntersecting ?? false);

    }, { rootMargin: '50px' });
    obs.observe(el);
    return () => obs.disconnect();
  }, [av?.kind, playVideo]);

  const isVideo = av?.kind === 'video' && av.url;
  const isImg = (av?.kind === 'photo' || av?.kind === 'gif') && av.url;

  /* сезонные рамки аватара (Новый год / весна / лето / осень) */
  const SEASONS = ['winter', 'spring', 'summer', 'autumn', 'halloween', 'love', 'galaxy', 'ocean'];
  const season = SEASONS.includes(String(fr.style)) ? String(fr.style) : null;

  const colorIdx = user ? hashCode(user.id) % AVATAR_COLORS.length : 0;
  const grad = `linear-gradient(135deg, ${AVATAR_COLORS[colorIdx]}, ${AVATAR_COLORS[(colorIdx + 3) % AVATAR_COLORS.length]})`;

  /* буква-аватар (вместо маскота): Telegram-стиль, цвет по имени */
  const monoName = String(user?.name || user?.username || title || av?.title || '?').trim();
  const monoChar = (monoName[0] || '·').toUpperCase();
  const monoIdx = monoName ? Math.abs(hashCode(monoName)) % AVATAR_COLORS.length : 0;
  const monoGrad = user ? grad : `linear-gradient(135deg, ${AVATAR_COLORS[monoIdx]}, ${AVATAR_COLORS[(monoIdx + 3) % AVATAR_COLORS.length]})`;

  const borderRadius = sh === 'circle' ? '50%' : '32%';

  const frameWrap = fr.style !== 'none' && !season ? { padding: 2.5, background:
      fr.style === 'solid' ? (fr.color || 'var(--accent)') :
      fr.style === 'neon' ? `conic-gradient(from 0deg, ${fr.color || '#7ad0ff'}, #ff5ec4, ${fr.color || '#7ad0ff'})` :
      `conic-gradient(from 0deg, ${fr.color || '#ff9158'}, #ffe29a, #7ad0ff, #b875ff, ${fr.color || '#ff9158'})`,
    filter: fr.style === 'neon' ? 'drop-shadow(0 0 3px rgba(122,208,255,.8))' : undefined,
  } : null;

  return (
    <div className={`avatar-wrap ${className ?? ''}`} style={{ width: size, height: size, position: 'relative', flexShrink: 0 }} title={title}>
      {story ? (
        <div className={`story-ring ${story === 'seen' ? 'seen' : ''}`} style={{ width: size, height: size }} />
      ) : null}
      <div style={
        story
          ? { width: size - 7, height: size - 7, margin: 'auto', borderRadius, cursor: onClick ? 'pointer' : undefined }
          : frameWrap
            ? { ...frameWrap, width: size, height: size, borderRadius, cursor: onClick ? 'pointer' : undefined }
            : { width: '100%', height: '100%' }
      }>
        <div ref={ref} className="avatar" onClick={onClick}
          style={{ width: '100%', height: '100%', borderRadius, background: (isImg || isVideo) ? grad : (av?.url ? 'linear-gradient(160deg, #24344a, #0e1722)' : monoGrad), overflow: 'hidden', display: 'flex', alignItems: 'center', justifyContent: 'center', position: 'relative', cursor: onClick ? 'pointer' : undefined }}>
          {isImg && <img src={av.url} alt="" loading="lazy" draggable={false} style={{ width: '100%', height: '100%', objectFit: 'cover', display: 'block' }} />}
          {isVideo && (
            <video src={av.url} autoPlay={inView} loop muted={videoMuted} playsInline
              onDoubleClick={() => setVideoMuted(!videoMuted)}
              style={{ width: '100%', height: '100%', objectFit: 'cover', display: inView ? 'block' : 'none', backgroundColor: 'rgba(0,0,0,.25)' }} />
          )}
          {!(av?.url) ? <div className="avatar-mono" style={{ fontSize: Math.max(11, Math.round(size * 0.42)) }}>{monoChar}</div> : null}
          {badge}
        </div>
      </div>
      {season && (
        <span className={`ava-season s-${season}`} aria-hidden>
          <SeasonRing season={season} />
        </span>
      )}
    </div>
  );
}

/* ================= МОДАЛКА ================= */
export function Modal({
  title, children, onClose, width = 480, footer, className,
}: {
  title?: React.ReactNode;
  children: React.ReactNode;
  onClose: () => void;
  width?: number | string;
  footer?: React.ReactNode;
  className?: string;
}) {
  useEffect(() => {
    const h = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose(); };
    window.addEventListener('keydown', h);
    /* навигационная пилюля должна прятаться под полноэкранной модалкой */
    document.body.classList.add('modal-open');
    return () => {
      window.removeEventListener('keydown', h);
      document.body.classList.remove('modal-open');
    };
  }, [onClose]);

  /* Portal в body: модалки внутри стеклянных контейнеров (композер/шапка чата
     имеют backdrop-filter/transform) иначе позиционируются не от окна, а от
     контейнера — модалка «прилипает» низко и криво (отложенное сообщение) */
  return createPortal(
    <div className="modal-back" onMouseDown={(e) => { if (e.target === e.currentTarget) onClose(); }}>
      <div className={`modal glass ${className ?? ''}`} style={{ maxWidth: width }} onMouseDown={(e) => e.stopPropagation()}>
        {title != null && (
          <div className="modal-head">
            <div className="modal-title">{title}</div>
            <button className="btn-icon" onClick={onClose}><Icon name="close" size={20} /></button>
          </div>
        )}
        <div className="modal-body">{children}</div>
        {footer && <div className="modal-foot">{footer}</div>}
      </div>
    </div>,
    document.body,
  );
}

/* ================= КОНТЕКСТНОЕ МЕНЮ ================= */
const MenuCtx = createContext<{ close: () => void }>({ close: () => {} });
export const useMenuCtx = () => useContext(MenuCtx);

export interface MenuItem {
  label: string;
  icon?: string;
  danger?: boolean;
  onClick?: () => void;
  hidden?: boolean;
  sub?: MenuItem[];
}

export function ContextMenu({ x, y, items, onClose }: { x: number; y: number; items: MenuItem[]; onClose: () => void }) {
  const ref = useRef<HTMLDivElement>(null);
  const [pos, setPos] = useState({ x, y });
  const [openSub, setOpenSub] = useState<string | null>(null);

  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return;
    const r = el.getBoundingClientRect();
    let nx = x, ny = y;
    if (x + r.width > innerWidth - 8) nx = Math.max(8, x - r.width);
    if (y + r.height > innerHeight - 8) ny = Math.max(8, y - r.height);
    setPos({ x: nx, y: ny });
  }, [x, y]);

  useEffect(() => {
    const h = (e: MouseEvent) => {
      if (!ref.current?.contains(e.target as Node)) onClose();
    };
    const k = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose(); };
    setTimeout(() => document.addEventListener('mousedown', h), 0);
    window.addEventListener('keydown', k);
    return () => { document.removeEventListener('mousedown', h); window.removeEventListener('keydown', k); };
  }, [onClose]);

  return (
    <MenuCtx.Provider value={{ close: onClose }}>
      <div ref={ref} className="ctx-menu glass" style={{ left: pos.x, top: pos.y }}>
        {items.filter((it) => !it.hidden).map((it, i) => (
          <div key={i} className="ctx-item-wrap"
            onMouseEnter={() => setOpenSub(it.sub ? it.label : null)}>
            <button className={`ctx-item ${it.danger ? 'danger' : ''}`}
              onClick={() => {
                if (it.sub) return;
                it.onClick?.();
                onClose();
              }}>
              {it.icon && <Icon name={it.icon} size={17} />}
              <span>{it.label}</span>
              {it.sub && <Icon name="arrowNext" size={14} className="ctx-sub-arrow" />}
            </button>
            {it.sub && openSub === it.label && (
              <div className="ctx-menu sub glass" style={{ left: '100%', top: 0 }}>
                {it.sub.filter((x) => !x.hidden).map((s, j) => (
                  <button key={j} className={`ctx-item ${s.danger ? 'danger' : ''}`}
                    onClick={() => { s.onClick?.(); onClose(); }}>
                    {s.icon && <Icon name={s.icon} size={17} />}
                    <span>{s.label}</span>
                  </button>
                ))}
              </div>
            )}
          </div>
        ))}
      </div>
    </MenuCtx.Provider>
  );
}

