/* зубчатая/лучевая кромка кольца: чётные точки на rA, нечётные на rB,
   внутренний диск rIn вычитается evenodd — закрашивается только кайма */
function edgeRing(rA: number, rB: number, n: number, rIn: number): string {
  let d = '';
  for (let i = 0; i < n; i++) {
    const a1 = (Math.PI * 2 * i) / n - Math.PI / 2;
    const a2 = (Math.PI * 2 * (i + 0.5)) / n - Math.PI / 2;
    d += (i ? 'L' : 'M') + (50 + rA * Math.cos(a1)).toFixed(2) + ' ' + (50 + rA * Math.sin(a1)).toFixed(2) + ' ';
    d += 'L' + (50 + rB * Math.cos(a2)).toFixed(2) + ' ' + (50 + rB * Math.sin(a2)).toFixed(2) + ' ';
  }
  d += ' Z M' + (50 + rIn) + ' 50 A' + rIn + ' ' + rIn + ' 0 1 1 ' + (50 - rIn) + ' 50 A' + rIn + ' ' + rIn + ' 0 1 1 ' + (50 + rIn) + ' 50 Z';
  return d;
}

